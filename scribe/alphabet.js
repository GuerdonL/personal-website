/* ---- parsing ---- */
function parsePath(src) {
  // → array of strokes; each stroke = flat array of points [p0, c1, c2, p1, c1, c2, p2, ...]
  return src.split(';').map(s => {
    const tok = s.trim().replace(/([MCL])/g, ' $1 ').split(/[\s,]+/).filter(Boolean);
    const pts = []; let i = 0; let cur = null;
    while (i < tok.length) {
      const cmd = tok[i++];
      if (cmd === 'M') { cur = { x: +tok[i++], y: +tok[i++] }; pts.push(cur); }
      else if (cmd === 'C') {
        const c1 = { x: +tok[i++], y: +tok[i++] }, c2 = { x: +tok[i++], y: +tok[i++] }, p = { x: +tok[i++], y: +tok[i++] };
        pts.push(c1, c2, p); cur = p;
      } else if (cmd === 'L') {
        const p = { x: +tok[i++], y: +tok[i++] };
        pts.push({ x: cur.x + (p.x - cur.x) / 3, y: cur.y + (p.y - cur.y) / 3 },
                 { x: cur.x + 2 * (p.x - cur.x) / 3, y: cur.y + 2 * (p.y - cur.y) / 3 }, p);
        cur = p;
      } else throw new Error('bad path token ' + cmd);
    }
    return pts;
  });
}

